#!/usr/bin/env python3
"""native_hooks.py [GEN_DIR] - route listed translated functions through
native replacements (config/native.json: module -> {VA: native symbol}).

The translated body is renamed recomp_<mod>_<VA>_orig and a wrapper with the
original name calls the native function, or the original when fam_native_on
is 0 (FAMILIA_NATIVE=0). Direct calls, indirect calls and the dispatch table
all keep using the original name. Idempotent."""
import json, re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def hook_text(c, mod, va, native):
    name = f"recomp_{mod}_{va}"
    if f"{name}_orig(void)" in c:
        return c, False
    # the translated body: under a timing probe's wrapper it is <name>_probed,
    # and the native switch goes between the two (the probe times either path)
    body = f"{name}_probed" if f"void {name}_probed(void) {{" in c else name
    head = f"void {body}(void) {{"
    if head not in c:
        return c, False
    c = c.replace(head, f"void {name}_orig(void) {{", 1)
    c += (f"\n/* native replacement (tools/native_hooks.py, config/native.json) */\n"
          f"extern int fam_native_on;\nvoid {native}(void);\n"
          f"void {name}_orig(void);\n"
          f"void {body}(void) {{ if (fam_native_on) {{ {native}(); return; }} {name}_orig(); }}\n")
    return c, True

def probe_text(c, mod, va, pid):
    """Wraps whatever recomp_<mod>_<VA> is now (translated body or native
    wrapper) in an inclusive timer: runtime/probe.c, FAMILIA_PROBE=1."""
    name = f"recomp_{mod}_{va}"
    if f"{name}_probed(void)" in c:
        return c, False
    head = f"void {name}(void) {{"
    if head not in c:
        return c, False
    c = c.replace(head, f"void {name}_probed(void) {{", 1)
    c += (f"\n/* timing probe (tools/native_hooks.py, config/probes.json) */\n"
          f"extern int fam_probe_on; uint64_t fam_probe_in(int); void fam_probe_out(int, uint64_t);\n"
          f"void {name}_probed(void);\n"
          f"void {name}(void) {{ if (!fam_probe_on) {{ {name}_probed(); return; }} "
          f"uint64_t t = fam_probe_in({pid}); {name}_probed(); fam_probe_out({pid}, t); }}\n")
    return c, True

def apply_probes(gen):
    """config/probes.json: [[module, VA, label], ...] -> build/gen/probes.c
    (the label table) and a timing wrapper around each function."""
    path = ROOT / "config/probes.json"
    probes = json.loads(path.read_text()) if path.exists() else []
    for pid, (mod, va, label) in enumerate(probes):
        va = va.upper()
        for f in sorted((gen / mod).glob("f_*.c")):
            c = f.read_text()
            if f"void recomp_{mod}_{va}(void) {{" in c:
                c2, changed = probe_text(c, mod, va, pid)
                if changed:
                    f.write_text(c2)
                print(f"probe {pid}: {mod}!{va} {label} in {f.name}{'' if changed else ' (already)'}")
                break
        else:
            print(f"probe {mod}!{va}: not found", file=sys.stderr)
    rows = ",\n".join(f'    "{mod}!{va.upper()} {label}"' for mod, va, label in probes)
    (gen / "probes.c").write_text(
        "/* generated by tools/native_hooks.py from config/probes.json */\n"
        f"const char *const fam_probe_names[] = {{\n{rows}{',' if rows else ''}\n    0\n}};\n"
        f"const int fam_probe_count = {len(probes)};\n")

def main():
    gen = Path(sys.argv[1]) if len(sys.argv) > 1 else ROOT / "build/gen"
    cfg = json.loads((ROOT / "config/native.json").read_text())
    for mod, hooks in cfg.items():
        for va, native in hooks.items():
            va = va.upper()
            for f in sorted((gen / mod).glob("f_*.c")):
                c = f.read_text()
                if f"void recomp_{mod}_{va}(void) {{" in c or f"void recomp_{mod}_{va}_probed(void) {{" in c or f"recomp_{mod}_{va}_orig(void)" in c:
                    c2, changed = hook_text(c, mod, va, native)
                    if changed:
                        f.write_text(c2)
                    print(f"{mod}!{va} -> {native} in {f.name}{'' if changed else ' (already)'}")
                    break
            else:
                print(f"{mod}!{va}: not found", file=sys.stderr)
    apply_probes(gen)

if __name__ == "__main__":
    main()
