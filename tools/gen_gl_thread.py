#!/usr/bin/env python3
"""gen_gl_thread.py - writes runtime/gl_thread_gen.h from runtime/gl_funcs.h.

For every GL entry point the renderer uses it emits:
  - a record stub with the exact signature (installed in place of the loaded
    pointer when the GL thread is on): it copies the arguments, and any data
    a pointer argument points to, into the command queue;
  - a replay case that calls the real entry point on the GL thread.
Entry points that return a value or write through a pointer run
synchronously: the stub waits until the GL thread has executed them.
Pointer arguments with known sizes are copied (POINTER_DATA below); vertex
and index pointers are offsets into bound buffers, or client pointers, which
make the following draw synchronous (gl_thread.c)."""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = (ROOT / "runtime/gl_funcs.h").read_text()
funcs = re.findall(r"X\(([^,]+),\s*(\w+),\s*\(([^)]*)\)\)", src)

# name -> list of (arg index of pointer, C expression for its byte size, using a0..aN)
POINTER_DATA = {
    "glBufferData": [(2, "(size_t)a1")],
    "glBufferSubData": [(3, "(size_t)a2")],
    "glCompressedTexImage2D": [(7, "(size_t)a6")],
    "glTexImage2D": [(8, "fam_glt_pixels_size(a3, a4, a6, a7)")],
    "glTexSubImage2D": [(8, "fam_glt_pixels_size(a4, a5, a6, a7)")],
    "glUniform3fv": [(2, "(size_t)a1 * 3 * sizeof(GLfloat)")],
    "glUniform4fv": [(2, "(size_t)a1 * 4 * sizeof(GLfloat)")],
    "glUniformMatrix4fv": [(3, "(size_t)a1 * 16 * sizeof(GLfloat)")],
    "glDeleteBuffers": [(1, "(size_t)a0 * sizeof(GLuint)")],
    "glDeleteFramebuffers": [(1, "(size_t)a0 * sizeof(GLuint)")],
    "glDeleteRenderbuffers": [(1, "(size_t)a0 * sizeof(GLuint)")],
    "glDeleteTextures": [(1, "(size_t)a0 * sizeof(GLuint)")],
}
# pointer-valued arguments passed through unchanged (buffer offsets / client pointers)
PASS_POINTER = {"glVertexAttribPointer": 5, "glDrawElements": 3}
# always synchronous even though void (strings, out pointers, readback, finish)
FORCE_SYNC = {"glShaderSource", "glBindAttribLocation", "glReadPixels", "glFinish",
              "glGetIntegerv", "glGetFloatv", "glGetProgramInfoLog", "glGetProgramiv",
              "glGetShaderInfoLog", "glGetShaderiv", "glGenBuffers", "glGenFramebuffers",
              "glGenRenderbuffers", "glGenTextures"}

out = ["/* generated by tools/gen_gl_thread.py from gl_funcs.h - do not edit */"]
enum = ["enum {"]
structs, stubs, replay = [], [], []
for ret, name, args in funcs:
    ret = ret.strip()
    types = [a.strip() for a in args.split(",")] if args.strip() not in ("", "void") else []
    params = ", ".join(f"{t} a{i}" for i, t in enumerate(types)) or "void"
    argn = ", ".join(f"a{i}" for i in range(len(types)))
    op = f"OP_{name}"
    enum.append(f"    {op},")
    sync = ret != "void" or name in FORCE_SYNC
    if sync:
        # args (and result) live in the caller's frame; the GL thread runs the call
        fields = "".join(f" {t} a{i};" for i, t in enumerate(types))
        rfield = f" {ret} r;" if ret != "void" else ""
        structs.append(f"typedef struct {{{fields}{rfield} int _dummy; }} S_{name};")
        stubs.append(
            f"static {ret} GL_APIENTRY rec_{name}({params}) {{\n"
            f"    S_{name} s = {{ {', '.join(f'a{i}' for i in range(len(types)))}{', ' if types else ''}" + ("0, " if ret != 'void' else "") + "0 };\n"
            f"    fam_glt_sync({op}, &s);\n"
            + (f"    return s.r;\n" if ret != "void" else "") + "}")
        call = f"real_{name}({', '.join(f's->a{i}' for i in range(len(types)))})"
        replay.append(f"    case {op}: {{ S_{name} *s = (S_{name} *)p; {'s->r = ' if ret != 'void' else ''}{call}; break; }}")
        continue
    ptrs = dict(POINTER_DATA.get(name, []))
    fields = "".join(f" {t} a{i};" for i, t in enumerate(types))
    structs.append(f"typedef struct {{{fields} int _dummy; }} C_{name};")
    body = [f"static void GL_APIENTRY rec_{name}({params}) {{"]
    extra = " + ".join(f"(a{i} ? FAM_GLT_ALIGN({sz}) : 0)" for i, sz in ptrs.items()) or "0"
    body.append(f"    size_t extra = {extra};")
    body.append(f"    uint8_t *q = fam_glt_begin({op}, sizeof(C_{name}) + extra);")
    body.append(f"    C_{name} *c = (C_{name} *)q; uint8_t *d = q + sizeof(C_{name}); (void)d;")
    for i, t in enumerate(types):
        if i in ptrs:
            body.append(f"    if (a{i}) {{ size_t n = {ptrs[i]}; memcpy(d, a{i}, n); c->a{i} = ({t})(uintptr_t)(d - q); d += FAM_GLT_ALIGN(n); }} else c->a{i} = 0;")
        else:
            body.append(f"    c->a{i} = a{i};")
    if name in PASS_POINTER:
        body.append(f"    fam_glt_note_pointer({op}, (const void *)a{PASS_POINTER[name]});")
    body.append("    fam_glt_end();")
    body.append("}")
    stubs.append("\n".join(body))
    callargs = []
    for i, t in enumerate(types):
        callargs.append(f"(c->a{i} ? ({t})(p + (uintptr_t)c->a{i}) : ({t})0)" if i in ptrs else f"c->a{i}")
    replay.append(f"    case {op}: {{ C_{name} *c = (C_{name} *)p; real_{name}({', '.join(callargs)}); break; }}")
enum.append("    OP_COUNT_GL\n};")
real = [f"static PFN_fam_{n} real_{n};" for _, n, _ in funcs]
install = ["static void fam_glt_install(void) {"]
install += [f"    real_{n} = fam_{n}; fam_{n} = (PFN_fam_{n})rec_{n};" for _, n, _ in funcs]
install.append("}")
uninstall = ["static void fam_glt_uninstall(void) {"]
uninstall += [f"    fam_{n} = real_{n};" for _, n, _ in funcs]
uninstall.append("}")
replayfn = ["static void fam_glt_replay_gl(int op, uint8_t *p) {", "    switch (op) {"] + replay + ["    default: break;", "    }", "}"]
text = "\n".join(out + enum + real + structs + stubs + install + uninstall + replayfn) + "\n"
(ROOT / "runtime/gl_thread_gen.h").write_text(text)
print(f"{len(funcs)} entry points, {sum(1 for r,n,a in funcs if r.strip()!='void' or n in FORCE_SYNC)} synchronous")
