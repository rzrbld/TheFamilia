#!/usr/bin/env python3
"""Emit vtable method order for COM interfaces from a MinGW-w64 header.
usage: com_vtables.py HEADER Iface [Iface...] -> a C header of slot names.
Only the method *order* is taken (an interface's ABI); no code is copied."""
import re, sys
src = open(sys.argv[1], encoding='latin1').read()
out = ["/* generated by tools/com_vtables.py from " + sys.argv[1].split('/')[-1] + ": vtable slot order */", "#pragma once"]
for iface in sys.argv[2:]:
    m = re.search(r'DECLARE_INTERFACE_(?:IID_)?\(\s*%s\s*,\s*(\w+)\s*(?:,\s*"[^"]*")?\s*\)\s*\{(.*?)\n\};' % iface, src, re.S)
    if not m:
        m = re.search(r'#define INTERFACE %s\s*\n\s*DECLARE_INTERFACE_(?:IID_)?\(\s*%s\s*,\s*(\w+)\s*(?:,\s*"[^"]*")?\s*\)\s*\{(.*?)\};' % (iface, iface), src, re.S)
    if not m: sys.exit("no " + iface)
    decl = re.findall(r'STDMETHOD_?\(\s*(?:[\w ]+?,\s*)?(\w+)\s*\)\s*\((.*?)\)\s*PURE', m.group(2), re.S)
    meths = [d[0] for d in decl]
    def argc(params):
        params = re.sub(r'\s+', ' ', params).strip()
        if params in ('THIS', ''): return 1
        rest = params.split('THIS_', 1)[1]
        return 1 + len([p for p in rest.split(',') if p.strip()])
    out.append(f"#define {iface.upper()}_SLOTS {len(meths)}")
    out.append(f"static const char *const {iface}_slot_names[] = {{ " + ", ".join(f'"{x}"' for x in meths) + " };")
    out.append(f"static const unsigned char {iface}_slot_argc[] = {{ " + ", ".join(str(argc(d[1])) for d in decl) + " };")
    for i, x in enumerate(meths): out.append(f"#define {iface.upper()}_{x} {i}")
    out.append(f"#define {iface.upper()}_FOR_EACH(X, P) " + " ".join(f"X(P, {i})" for i in range(len(meths))))
print("\n".join(out))
