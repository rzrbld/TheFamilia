#!/usr/bin/env python3
"""Extract enum constants and simple #define values with the given prefixes
from MinGW-w64 headers into a C header (values only)."""
import re, sys
hdr, prefixes = sys.argv[1], sys.argv[2:]
src = ''.join(open(f'{hdr}/{f}', encoding='latin1').read() for f in ('d3d8types.h', 'd3d8caps.h', 'd3d8.h'))
src = re.sub(r'/\*.*?\*/', '', src, flags=re.S)
vals = {}
def ev(expr):
    e = expr.strip().rstrip('L').rstrip('l')
    e = re.sub(r'\b(0x[0-9a-fA-F]+|\d+)[uUlL]+\b', r'\1', e)
    e = re.sub(r'MAKE_D3DHRESULT\(\s*(\d+)\s*\)', lambda m: str(0x88760000 | int(m.group(1))), e)
    e = re.sub(r'MAKE_D3DSTATUS\(\s*(\d+)\s*\)', lambda m: str(0x08760000 | int(m.group(1))), e)
    e = re.sub(r'MAKEFOURCC\(\s*\'(.)\'\s*,\s*\'(.)\'\s*,\s*\'(.)\'\s*,\s*\'(.)\'\s*\)', lambda m: str(sum(ord(c) << (8*i) for i, c in enumerate(m.groups()))), e)
    e = re.sub(r'\(\s*(DWORD|ULONG|HRESULT|D3DFORMAT|int|UINT)\s*\)', '', e)
    for k in sorted(vals, key=len, reverse=True): e = re.sub(r'\b%s\b' % k, str(vals[k]), e)
    if re.search(r'[A-Za-z_]', re.sub(r'0x[0-9a-fA-F]+', '', e)): return None
    try: return eval(e) & 0xFFFFFFFF
    except Exception: return None
for body in re.findall(r'typedef\s+enum\s+\w*\s*\{(.*?)\}', src, re.S):
    cur = -1
    for item in body.split(','):
        item = item.strip()
        if not item or item.startswith('#'): continue
        m = re.match(r'(\w+)\s*(?:=\s*(.+))?$', item, re.S)
        if not m: continue
        v = ev(m.group(2)) if m.group(2) else cur + 1
        if v is None: continue
        cur = v; vals[m.group(1)] = v
for name, expr in re.findall(r'^\s*#define\s+(\w+)\s+(.+?)\s*$', src, re.M):
    v = ev(expr)
    if v is not None: vals[name] = v
print('/* generated by tools/enums.py: D3D8 constant values */\n#pragma once')
for k, v in vals.items():
    if any(k.startswith(p) for p in prefixes): print(f'#define {k} 0x{v:X}u')
