#!/usr/bin/env python3
"""Emit guest-ABI (i386) C structs for D3D8 types from a MinGW-w64 header's
field order. Every Win32 scalar here is 4 bytes; arrays/nested types listed
in SPECIAL. Output uses fixed-width types so the host layout equals i386's."""
import re, sys
T4 = {'DWORD':'uint32_t','UINT':'uint32_t','ULONG':'uint32_t','WINBOOL':'uint32_t','BOOL':'uint32_t','HWND':'uint32_t',
      'D3DFORMAT':'uint32_t','D3DDEVTYPE':'uint32_t','D3DMULTISAMPLE_TYPE':'uint32_t','D3DSWAPEFFECT':'uint32_t',
      'D3DRESOURCETYPE':'uint32_t','D3DPOOL':'uint32_t','D3DLIGHTTYPE':'uint32_t','float':'float','FLOAT':'float','INT':'int32_t','void*':'uint32_t'}
NESTED = {'D3DCOLORVALUE':'fam_D3DCOLORVALUE','D3DVECTOR':'fam_D3DVECTOR','LARGE_INTEGER':'uint64_t','GUID':'fam_GUID'}
def emit(src, name, out):
    m = re.search(r'typedef struct _?%s\w*\s*\{(.*?)\}\s*%s\s*;' % (name, name), src, re.S)
    if not m: sys.exit('no ' + name)
    body = re.sub(r'/\*.*?\*/', '', m.group(1), flags=re.S)
    out.append(f"typedef struct {{  /* {name} (i386 layout) */")
    for line in body.split(';'):
        line = line.strip()
        if not line or line.startswith('#'): continue
        mm = re.match(r'(\w+\s*\*?)\s+(.*)$', line, re.S)
        if not mm: sys.exit(f'{name}: cannot parse {line!r}')
        t = mm.group(1).replace(' ', '')
        ct = T4.get(t) or NESTED.get(t) or ('char' if t == 'char' else None)
        if not ct: sys.exit(f'{name}: type {t}')
        for decl in mm.group(2).split(','):
            dm = re.match(r'\s*(\w+)\s*(\[(\w+)\])?\s*$', decl)
            if not dm: sys.exit(f'{name}: cannot parse {decl!r}')
            out.append(f"    {ct} {dm.group(1)}{'['+dm.group(3)+']' if dm.group(3) else ''};")
    out.append(f"}} fam_{name};")
hdr = sys.argv[1]
src = ''.join(open(f'{hdr}/{f}', encoding='latin1').read() for f in ('d3d8types.h', 'd3d8caps.h', 'd3d8.h'))
src = src.replace('MAX_DEVICE_IDENTIFIER_STRING', '512')
out = ["/* generated by tools/struct_layouts.py: guest i386 layouts of D3D8 structs */", "#pragma once", "#include <stdint.h>",
       "typedef struct { float r, g, b, a; } fam_D3DCOLORVALUE;", "typedef struct { float x, y, z; } fam_D3DVECTOR;",
       "typedef struct { uint32_t d1; uint16_t d2, d3; uint8_t d4[8]; } fam_GUID;"]
for n in sys.argv[2:]: emit(src, n, out)
print("\n".join(out))
